"""The files of the catalogue that the game reads: written from the albums, never by hand.

- media/lua/shared/JukeboxMoon/CatalogData.lua: JukeboxMoonCatalog for Catalog.lua. Kahlua (the game's Lua, 42.21)
  breaks accented letters written as they are: every byte that is not plain ASCII is written as \\ddd.
- media/scripts/JukeboxMoon_catalog.txt: one CD item per album; JukeboxMoon_sounds.txt: one sound per piece.
- media/lua/shared/Translate/IT|EN/ItemName.json: the CDs' names («CD: <album>»).
- media/textures/Item_JukeboxMoon_CD_<n>.png (the icon, 32x32) and JukeboxMoon/Cover_<n>.png (256x256).
"""

from __future__ import annotations

import hashlib
import io
import json
from dataclasses import dataclass

from PIL import Image, ImageDraw

from .audio import OVERLAP_MS, SEGMENT_MS

MODULE = "JukeboxMoon"
DISTANCE_MIN = 3
DISTANCE_MAX = 40
ICON = 32
COVER = 256


@dataclass
class TrackOut:
    key: int
    id: str
    n: int
    title: str
    artist: str
    ms: int
    segments: int


@dataclass
class AlbumOut:
    key: int
    id: str
    title: str
    artist: str
    year: int | None
    loot: float
    archived: bool
    tracks: list[TrackOut]
    cover: bytes | None      # the source image, or None for a drawn one

    @property
    def item(self) -> str:
        return f"{MODULE}.CD_{self.key}"


def lua_string(text: str) -> str:
    """A Lua string literal with only ASCII inside: other bytes as \\ddd (always three digits), quotes escaped."""
    out = ['"']
    for byte in str(text).encode("utf-8"):
        if byte in (0x22, 0x5C):
            out.append("\\" + chr(byte))
        elif 32 <= byte < 127:
            out.append(chr(byte))
        else:
            out.append(f"\\{byte:03d}")
    out.append('"')
    return "".join(out)


def _number(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def catalog_lua(version: str, albums: list[AlbumOut]) -> str:
    lines = [
        "-- Generated by tools/jukebox (python -m tools.jukebox build): do not edit. The catalogue of Jukebox (Moon).",
        "JukeboxMoonCatalog = {",
        f"\tversion = {lua_string(version)},",
        f"\tsegmentMs = {SEGMENT_MS},",
        f"\toverlapMs = {OVERLAP_MS},",
        "\talbums = {",
    ]
    for a in albums:
        lines.append("\t\t{")
        lines.append(f"\t\t\tkey = {a.key}, id = {lua_string(a.id)}, item = {lua_string(a.item)},")
        lines.append(f"\t\t\ttitle = {lua_string(a.title)}, artist = {lua_string(a.artist)},")
        lines.append(f"\t\t\tyear = {a.year if a.year is not None else 'nil'}, loot = {_number(a.loot)}, "
                     f"archived = {'true' if a.archived else 'false'},")
        lines.append(f"\t\t\tcover = {lua_string(f'media/textures/JukeboxMoon/Cover_{a.key}.png')},")
        lines.append("\t\t\ttracks = {")
        for t in a.tracks:
            lines.append(f"\t\t\t\t{{ key = {t.key}, id = {lua_string(t.id)}, n = {t.n}, title = {lua_string(t.title)}, "
                         f"artist = {lua_string(t.artist)}, ms = {t.ms}, segments = {t.segments} }},")
        lines.append("\t\t\t},")
        lines.append("\t\t},")
    lines += ["\t},", "}", ""]
    return "\n".join(lines)


def items_script(albums: list[AlbumOut]) -> str:
    lines = ["module JukeboxMoon", "{", "    imports", "    {", "        Base", "    }", ""]
    for a in albums:
        lines += [
            f"    item CD_{a.key}",
            "    {",
            "        DisplayCategory = Entertainment,",
            "        ItemType = base:normal,",
            "        Weight = 0.1,",
            f"        Icon = JukeboxMoon_CD_{a.key},",
            "        WorldStaticModel = Disk,",
            "        Tooltip = Tooltip_JukeboxMoon_CD,",
            "    }",
            "",
        ]
    lines += ["}", ""]
    return "\n".join(lines)


def sound_path(track_key: int, segment: int) -> str:
    return f"media/sound/jukeboxmoon/t{track_key}/s{segment:03d}.ogg"


def sounds_script(albums: list[AlbumOut]) -> str:
    lines = ["module JukeboxMoon", "{"]
    for a in albums:
        for t in a.tracks:
            for k in range(t.segments):
                lines += [
                    f"    sound JukeboxMoon_T{t.key}_S{k}",
                    "    {",
                    "        category = JukeboxMoon,",
                    "        master = Ambient,",
                    "        clip",
                    "        {",
                    f"            file = {sound_path(t.key, k)},",
                    f"            distanceMin = {DISTANCE_MIN},",
                    f"            distanceMax = {DISTANCE_MAX},",
                    "        }",
                    "    }",
                ]
    lines += ["}", ""]
    return "\n".join(lines)


def item_names(albums: list[AlbumOut]) -> str:
    names = {a.item: f"CD: {a.title}" for a in albums}
    return json.dumps(names, ensure_ascii=False, indent=4, sort_keys=True) + "\n"


def _png(image: Image.Image) -> bytes:
    out = io.BytesIO()
    image.save(out, format="PNG", optimize=True)
    return out.getvalue()


def _colour(seed: str) -> tuple[int, int, int]:
    h = hashlib.sha256(seed.encode()).digest()
    return 60 + h[0] % 150, 60 + h[1] % 150, 60 + h[2] % 150


def cover_image(album: AlbumOut) -> Image.Image:
    """The album's cover as a square, or a drawn one (a disc in the album's colour) when it has none."""
    if album.cover:
        image = Image.open(io.BytesIO(album.cover)).convert("RGB")
        side = min(image.size)
        left, top = (image.width - side) // 2, (image.height - side) // 2
        return image.crop((left, top, left + side, top + side)).resize((COVER, COVER), Image.LANCZOS)
    image = Image.new("RGB", (COVER, COVER), _colour(album.id))
    draw = ImageDraw.Draw(image)
    draw.ellipse((28, 28, COVER - 28, COVER - 28), fill=(225, 225, 230), outline=(40, 40, 40), width=4)
    draw.ellipse((COVER // 2 - 30, COVER // 2 - 30, COVER // 2 + 30, COVER // 2 + 30), fill=_colour(album.id + "c"))
    draw.ellipse((COVER // 2 - 8, COVER // 2 - 8, COVER // 2 + 8, COVER // 2 + 8), fill=(30, 30, 30))
    return image


def icon_image(cover: Image.Image) -> Image.Image:
    """32x32: the cover inside a disc, the rest transparent, like the game's CD icon."""
    big = 128
    disc = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    mask = Image.new("L", (big, big), 0)
    ImageDraw.Draw(mask).ellipse((2, 2, big - 3, big - 3), fill=255)
    disc.paste(cover.resize((big, big), Image.LANCZOS).convert("RGBA"), (0, 0), mask)
    draw = ImageDraw.Draw(disc)
    draw.ellipse((2, 2, big - 3, big - 3), outline=(30, 30, 30, 255), width=4)
    draw.ellipse((big // 2 - 14, big // 2 - 14, big // 2 + 14, big // 2 + 14), fill=(220, 220, 225, 255),
                 outline=(30, 30, 30, 255), width=3)
    draw.ellipse((big // 2 - 5, big // 2 - 5, big // 2 + 5, big // 2 + 5), fill=(0, 0, 0, 0))
    return disc.resize((ICON, ICON), Image.LANCZOS)


def public_files(version: str, albums: list[AlbumOut]) -> dict[str, bytes]:
    """Every file of the public catalogue, by its path in the mod (from the mod's folder: 42/media/...)."""
    files: dict[str, bytes] = {
        "42/media/lua/shared/JukeboxMoon/CatalogData.lua": catalog_lua(version, albums).encode("ascii"),
        "42/media/scripts/JukeboxMoon_catalog.txt": items_script(albums).encode("ascii"),
        "42/media/scripts/JukeboxMoon_sounds.txt": sounds_script(albums).encode("ascii"),
        "42/media/lua/shared/Translate/IT/ItemName.json": item_names(albums).encode("utf-8"),
        "42/media/lua/shared/Translate/EN/ItemName.json": item_names(albums).encode("utf-8"),
    }
    for a in albums:
        cover = cover_image(a)
        files[f"42/media/textures/JukeboxMoon/Cover_{a.key}.png"] = _png(cover)
        files[f"42/media/textures/Item_JukeboxMoon_CD_{a.key}.png"] = _png(icon_image(cover))
    return files
